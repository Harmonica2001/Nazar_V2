# ---------------------- GATE 1 ----------------------
    
def gate_1(source, model, conf_threshold):
    global gate1_bool, item
    
    item = None
    cap = cv2.VideoCapture(source)

    THINNESS_THRESHOLD = 0.3   # Adjust 0.2–0.4 depending on strictness

    while True:
        ret, frame = cap.read()
        if not ret:
            break

        results = model(frame, verbose=False)
        detected = 0

        for result in results:
            for box in result.boxes:
                confidence = float(box.conf)
                class_id = int(box.cls)
                class_name = model.names[class_id].lower()

                if confidence < conf_threshold:
                    continue

                # ---------------- KNIFE SHAPE CHECK ----------------
                if class_name == "knife":

                    x1, y1, x2, y2 = map(float, box.xyxy[0])
                    width = x2 - x1
                    height = y2 - y1

                    if width <= 0 or height <= 0:
                        continue

                    # Orientation-independent thinness ratio
                    thinness_ratio = min(width, height) / max(width, height)

                    print(f"Knife detected — Thinness ratio: {thinness_ratio:.2f}")

                    if thinness_ratio >= THINNESS_THRESHOLD:
                        print("Knife rejected — shape not thin enough")
                        continue  # Reject this detection

                    print("Knife accepted — shape valid")
                    item = "knife"

                elif class_name == "alcohol":
                    item = "alcohol"

                detected = 1
                print(f"Detected: {class_name} ({confidence:.2f})")
                gate1_bool = True
                cap.release()
                return True

        if detected == 0:
            print(0)

        if cv2.waitKey(1) & 0xFF == ord('q'):
            break

    cap.release()
    cv2.destroyAllWindows()
    return False



# ---------------------- GATE 2 ----------------------

def gate_2(source, model, conf_threshold):

    cap = cv2.VideoCapture(source)
    start_time = None

    while True:
        ret, frame = cap.read()
        if not ret:
            break

        results = model(frame, verbose=False)

        person_detected = False
        for result in results:
            for box in result.boxes:
                confidence = float(box.conf)
                cls = int(box.cls)

                if cls == 0 and confidence > conf_threshold:
                    person_detected = True
                    break

        if person_detected:
            if start_time is None:
                start_time = time.time()
            elif time.time() - start_time >= 1:
                print("Person also detected")
                return True
        else:
            return False

        if cv2.waitKey(1) & 0xFF == ord('q'):
            break

    cap.release()
    cv2.destroyAllWindows()
    return False


