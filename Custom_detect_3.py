def send_email_alert(image_path, item):

    msg = EmailMessage()
    msg["Subject"] = f"⚠️ Security Alert — Human Carrying {item}"
    msg["From"] = EMAIL_SENDER
    msg["To"] = EMAIL_RECEIVER

